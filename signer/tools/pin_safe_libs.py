#!/usr/bin/env python3
"""Pins Safe's SignMessageLib and MultiSendCallOnly (v1.4.1) into signer/winterlock_signer/safe_libs.json, from the
release build that contracts/setup.sh makes (solc 0.7.6, optimizer off, EVM istanbul).

A Safe transaction that delegatecalls a library runs the library's code as the Safe, so the signer only builds such
calls to code it recognises: the runtime code of the release build without its trailing CBOR metadata (which holds
the source's IPFS hash and is never executed). The canonical deployments match it: checked against Sourcify's
verified runtime code for both (2026-11-05), whose full keccak256 is the codeHash safe-deployments lists, pinned here
too. Addresses and code hashes: safe-deployments, src/assets/v1.4.1/{sign_message_lib,multi_send_call_only}.json.
"""
import json
import os
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
ROOT = os.path.dirname(os.path.dirname(HERE))
sys.path.insert(0, os.path.dirname(HERE))
from winterlock_signer.keccak import keccak256  # noqa: E402
from winterlock_signer.safelibs import strip_metadata  # noqa: E402

BUILD = os.path.join(ROOT, "contracts/lib/safe-smart-account-v1.4.1/build/forge-out")
CANONICAL = {
    "SignMessageLib": ("0xd53cd0aB83D845Ac265BE939c57F53AD838012c9",
                       "0x525c754a46b79e05543a59bb61e8de3c9eee0d955a59352409cbe67ea1077528"),
    "MultiSendCallOnly": ("0x9641d764fc13c8B624c04430C7356C1C7C8102e2",
                          "0xecd5bd14a08c5d2122379900b2f272bdf107a7e92423c10dd5fe3254386c9939"),
}


def built(name) -> bytes:
    with open(os.path.join(BUILD, f"{name}.sol", f"{name}.json")) as f:
        return bytes.fromhex(json.load(f)["deployedBytecode"]["object"][2:])


def main():
    out = {"_comment": "Generated by signer/tools/pin_safe_libs.py from Safe v1.4.1's release build; do not edit.",
           "release": "v1.4.1"}
    for name, (address, code_hash) in CANONICAL.items():
        code = strip_metadata(built(name))
        out[name] = {"address": address, "codeHash": code_hash, "codeWithoutMetadataHash": "0x" + keccak256(code).hex(),
                     "codeWithoutMetadataLength": len(code)}
    path = os.path.join(os.path.dirname(HERE), "winterlock_signer", "safe_libs.json")
    with open(path, "w") as f:
        json.dump(out, f, indent=1)
        f.write("\n")
    print(f"pinned {', '.join(CANONICAL)} into {os.path.relpath(path, ROOT)}")


if __name__ == "__main__":
    main()
