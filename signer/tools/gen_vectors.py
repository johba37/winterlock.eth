#!/usr/bin/env python3
"""Known answers from the repository's Solidity reference signers, for signer/tests/test_vectors.py.

Builds signer/tests/sol/SignerVectors.sol (WotsSigner, WotsTree and StatelessSigner from contracts/test/utils) and
contracts/bench/safe/SafeSignerHelper.sol (the v1 live test's signer: WOTS trees, transaction signatures in v1's
layout, which v2's adds a device byte to, and certificates) with forge into a temporary directory, deploys them on a
local anvil, asks them for keys, trees and signatures with eth_call, and writes inputs and outputs to
signer/tests/vectors/solidity.json. The helper's trees use v2's tree seed for device 0 (passed in). The deterministic
addresses (stateless verifier, shared WOTS verifier, WinterlockOwner v2 implementation, factory, members' proxy
owners) come from SafeOwnerDeployment's own predictions: contracts/script/DeploySafeOwner.s.sol run locally, without
an RPC or broadcast, with a dummy deployer key. All inputs are public test labels. The v2 digests and signature kinds
are checked against the compiled contract itself on anvil (tests/test_owner_v2.py).

usage: signer/.venv/bin/python signer/tools/gen_vectors.py
"""
import json
import os
import subprocess
import sys
import tempfile
import time

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
from devchain import CONTRACTS, ROOT, SIGNER, Anvil, artifact_code, deploy, forge_build, tool  # noqa: E402

from winterlock_signer import abi, owner  # noqa: E402
from winterlock_signer.abi import b2h  # noqa: E402
from winterlock_signer.keccak import keccak256  # noqa: E402
from winterlock_signer.safe import SafeTx  # noqa: E402

GAS = 4_000_000_000


def k(label: str) -> bytes:
    return keccak256(label.encode())


def forge_predictions(key: bytes) -> dict:
    """SafeOwnerDeployment's addresses for `key`, from DeploySafeOwner.s.sol's log (local simulation only)"""
    env = {k_: v for k_, v in os.environ.items() if k_ not in ("ALCHEMY_API_KEY", "SAFE_API_KEY", "DEPLOYER_PRIVATE_KEY")}
    env.update(DEPLOYER_PRIVATE_KEY="0x01", WINTERLOCK_KEY=b2h(key))
    out = subprocess.run([tool("forge"), "script", "script/DeploySafeOwner.s.sol"], cwd=CONTRACTS, env=env,
                         capture_output=True, text=True, check=True).stdout
    names = {"stateless verifier": "verifier", "WOTS verifier": "wots_verifier", "implementation": "implementation",
             "factory": "factory", "owner": "owner"}
    found = {}
    for line in out.splitlines():
        line = line.strip()
        for label, name in names.items():
            if line.startswith(f"{label}: to deploy at ") or line.startswith(f"{label}: deployed at "):
                found[name] = abi.checksum(line.split(" at ")[1].strip())
    assert set(found) == set(names.values()), out[-2000:]
    return dict(found, key=b2h(key))

def main():
    out = {"_comment": "Generated by signer/tools/gen_vectors.py from the Solidity reference signers; do not edit."}
    out["commit"] = subprocess.run(["git", "rev-parse", "--short", "HEAD"], capture_output=True, text=True,
                                   cwd=ROOT).stdout.strip()
    out["forge"] = subprocess.run([tool("forge"), "--version"], capture_output=True, text=True).stdout.split("\n")[0]
    with tempfile.TemporaryDirectory() as tmp:
        build = forge_build(["../signer/tests/sol/SignerVectors.sol", "bench/safe/SafeSignerHelper.sol"], tmp)
        chain = Anvil()
        try:
            rpc, acct = chain.rpc, chain.account
            vec = deploy(rpc, acct, artifact_code(f"{build}/SignerVectors.sol/SignerVectors.json"))
            helper = deploy(rpc, acct, artifact_code(f"{build}/SafeSignerHelper.sol/SafeOwnerSignerHelper.json"))

            def call(to, sig, types, values):
                return rpc.eth_call(to, abi.calldata(sig, types, values), gas=GAS)

            t0 = time.time()
            wots = {"leaf": [], "sign": [], "tree": []}
            for i, key_index in enumerate([0, 7, 1 << 40 | 5]):
                seed = int.from_bytes(k(f"wots seed {i}")[:16], "big")
                sk = k(f"wots sk {i}")
                leaf = call(vec, "wotsLeaf(uint128,bytes32,uint256)", ["uint256", "bytes32", "uint256"],
                            [seed, sk, key_index])
                wots["leaf"].append({"seed": hex(seed), "skSeed": b2h(sk), "keyIndex": key_index, "leaf": b2h(leaf)})
            for i, key_index in enumerate([0, 1, 1000, (1 << 40) + 5]):
                seed = int.from_bytes(k(f"wots seed {i}")[:16], "big")
                sk, msg = k(f"wots sk {i}"), k(f"wots message {i}")
                sig = abi.dec_bytes(call(vec, "wotsSign(uint128,bytes32,uint256,bytes32)",
                                         ["uint256", "bytes32", "uint256", "bytes32"], [seed, sk, key_index, msg]))
                wots["sign"].append({"seed": hex(seed), "skSeed": b2h(sk), "keyIndex": key_index, "message": b2h(msg),
                                     "sig": b2h(sig)})
            for i, (height, kk, index) in enumerate([(4, 4, 0), (4, 4, 13), (6, 3, 7), (10, 4, 5)]):
                seed = int.from_bytes(k(f"tree seed {i}")[:16], "big")
                sk = k(f"tree sk {i}")
                ret = call(vec, "wotsTree(uint128,bytes32,uint256,uint256,uint256)",
                           ["uint256", "bytes32", "uint256", "uint256", "uint256"], [seed, sk, height, kk, index])
                wots["tree"].append({"seed": hex(seed), "skSeed": b2h(sk), "height": height, "k": kk, "index": index,
                                     "root": b2h(abi.dec_word(ret, 0)), "path": b2h(abi.dec_bytes(ret, 1))})
            out["wots"] = wots
            print(f"wots vectors: {time.time() - t0:.1f} s")

            t0 = time.time()
            stateless = []
            for i, b in enumerate([10, 10, 8]):
                seed = k(f"stateless seed {i}")
                pk = abi.dec_word(call(vec, "statelessKey(bytes32,uint256)", ["bytes32", "uint256"], [seed, b]))
                sigs = []
                for j in range(2 if b == 10 else 1):
                    msg = k(f"stateless message {i} {j}")
                    sig = abi.dec_bytes(call(vec, "statelessSign(bytes32,uint256,bytes32)",
                                             ["bytes32", "uint256", "bytes32"], [seed, b, msg]))
                    sigs.append({"message": b2h(msg), "sig": b2h(sig)})
                stateless.append({"seed": b2h(seed), "b": b, "publicKey": b2h(pk), "signatures": sigs})
            out["stateless"] = stateless
            print(f"stateless vectors: {time.time() - t0:.1f} s")

            # the live test's signer: owner-level formats (bench/safe/SafeSignerHelper.sol)
            t0 = time.time()
            tag = k("winterlock signer vectors: public tag")
            chain_id, safe = 11155111, abi.checksum("0x5B81D3ce1Ca48be48F154D8AD060Cf9f883E86B2")
            member = 0
            pk = abi.dec_word(call(helper, "publicKey(bytes32,uint256)", ["bytes32", "uint256"], [tag, member]))
            out["deployment"] = [forge_predictions(pk), forge_predictions(k("another stateless key"))]
            own = out["deployment"][0]["owner"]  # the member's proxy owner, as SafeOwnerDeployment predicts it
            start = 0
            seed = owner.tree_seed(chain_id, own, safe, 0, 0, start)  # device 0, generation 0
            ret = call(helper, "tree(bytes32,uint256,uint256,address,uint64,uint128)",
                       ["bytes32", "uint256", "uint256", "address", "uint256", "uint256"],
                       [tag, member, chain_id, safe, start, seed])
            h = {"tag": b2h(tag), "member": member, "chainId": chain_id, "safe": safe, "start": start,
                 "publicKey": b2h(pk), "owner": own, "treeSeed": hex(seed), "root": b2h(abi.dec_word(ret, 0)),
                 "height": abi.dec_uint(ret, 1), "tx": []}
            txs = [(SafeTx(to=safe, value=0, nonce=0), 0),
                   (SafeTx(to="0x000000000000000000000000000000000000dEaD", value=10**15, nonce=3,
                           data=abi.calldata("transfer(address,uint256)", ["address", "uint256"],
                                             ["0x000000000000000000000000000000000000bEEF", 12345])), 1)]
            for t, slot in txs:
                ret = call(helper, "txSignature(bytes32,uint256,uint256,address,uint64,uint128,uint256,bytes32[10])",
                           ["bytes32", "uint256", "uint256", "address", "uint256", "uint256", "uint256", "bytes32[10]"],
                           [tag, member, chain_id, safe, start, seed, slot, t.words()])
                h["tx"].append({"safeTx": t.to_json(), "slot": slot, "data": b2h(abi.dec_bytes(ret, 0)),
                                "hash": b2h(abi.dec_word(ret, 1))})
            digest = owner.certificate_digest(chain_id, own, safe, 0, 0, abi.h2b(h["root"])[:24], h["height"], start)
            cert = abi.dec_bytes(call(helper, "certificate(bytes32,uint256,bytes32)", ["bytes32", "uint256", "bytes32"],
                                      [tag, member, digest]))
            h["certificate"] = {"digest": b2h(digest), "sig": b2h(cert)}
            out["helper"] = h
            print(f"helper vectors: {time.time() - t0:.1f} s")
        finally:
            chain.close()
    path = os.path.join(SIGNER, "tests", "vectors", "solidity.json")
    os.makedirs(os.path.dirname(path), exist_ok=True)
    with open(path, "w") as f:
        json.dump(out, f, indent=1)
        f.write("\n")
    print(f"wrote {os.path.relpath(path, ROOT)} ({os.path.getsize(path):,} bytes)")


if __name__ == "__main__":
    main()
